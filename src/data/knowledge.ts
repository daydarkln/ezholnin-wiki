export function getArticleBySlug(slug: string): KnowledgeArticle | undefined {
  return knowledgeArticles.find((article) => article.slug === slug)
}

export function getArticleById(id: string): KnowledgeArticle | undefined {
  return knowledgeArticles.find((article) => article.id === id)
}

export function getCategoryById(id: KnowledgeCategoryId): KnowledgeCategory {
  const category = knowledgeCategories.find((item) => item.id === id)

  if (!category) {
    throw new Error(`Unknown knowledge category: ${id}`)
  }

  return category
}

export function getArticlesByCategory(categoryId: KnowledgeCategoryId): KnowledgeArticle[] {
  return knowledgeArticles.filter((article) => article.categoryId === categoryId)
}
